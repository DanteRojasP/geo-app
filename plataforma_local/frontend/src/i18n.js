const MONTHS_SHORT = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  es: ['Ene', 'Feb', 'Mar', 'Abr', 'May', 'Jun', 'Jul', 'Ago', 'Sep', 'Oct', 'Nov', 'Dic'],
}
const MONTH_LETTERS = {
  en: ['J', 'F', 'M', 'A', 'M', 'J', 'J', 'A', 'S', 'O', 'N', 'D'],
  es: ['E', 'F', 'M', 'A', 'M', 'J', 'J', 'A', 'S', 'O', 'N', 'D'],
}
const LOCALES = { en: 'en-US', es: 'es-PE' }

function initialLang() {
  if (typeof window === 'undefined') return DEFAULT
  const fromUrl = new URLSearchParams(window.location.search).get('lang')
  const saved = fromUrl || window.localStorage?.getItem('firecal.lang')
  return LANGS.includes(saved) ? saved : DEFAULT
}

let current = initialLang()

export const getLang = () => current
export function setLang(lang) {
  if (!LANGS.includes(lang)) return
  current = lang
  try { window.localStorage?.setItem('firecal.lang', lang) } catch { /* modo privado */ }
  document.documentElement.lang = lang
  document.title = tr('doc.title')
}

// tr('clave', { var: valor }) -> texto en el idioma actual (respaldo: inglés, luego la clave).
export function tr(key, vars = {}) {
  const text = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
}

export const months = () => MONTHS_SHORT[current] || MONTHS_SHORT.en
export const monthLetters = () => MONTH_LETTERS[current] || MONTH_LETTERS.en
export const locale = () => LOCALES[current] || LOCALES.en
